def histogram(values, bins=8, width=44):
    lo, hi = min(values), max(values)
    if hi <= lo:
        hi = lo + 1e-9
    edges = np.linspace(lo, hi, bins + 1)
    counts, _ = np.histogram(values, bins=edges)
    lines = []
    for i in range(bins):
        bar = "#" * int(round(width * counts[i] / max(counts.max(), 1)))
        lines.append(f"[{edges[i]:6.2f},{edges[i+1]:6.2f}) | {bar} {counts[i]}")
    return lines


def run_benchmark(args) -> dict:
    geom = dtp.default_geometry()
    modulation = dtp.default_modulation(args.hr, args.amp)
    dom = dtp.build_domain(args.grid, geom)
    q_b = dtp.target_flow_m3s(geom)
    out_dir = args.out
    cmp_dir = os.path.join(out_dir, "compare")
    os.makedirs(cmp_dir, exist_ok=True)
    os.makedirs(out_dir, exist_ok=True)

    print(f"[compare] grid {args.grid}^3, Q_blood = {q_b*1e6:.2f} mL/s")
    print(f"[compare] baseline velocity solve (decoupled cache build) ...")
    t0 = time.perf_counter()
    sol_base = dtp.solve_steady_stokes(dom, q_b)
    t_cache = time.perf_counter() - t0
    cache_path = os.path.join(out_dir, "u_cache.npz")
    dtp.save_velocity_cache(cache_path, sol_base, dom, modulation, {"q_target_m3s": q_b})
    print(f"[compare]   {t_cache:.1f}s  Q = {sol_base['q_m3s']*1e6:.2f} mL/s  "
          f"res = {sol_base['residual']:.2e}")

    grid = dtp.injection_grid(_parse(args.volumes), _parse(args.rates), _parse(args.diffusivities))
    print(f"[compare] {len(grid)} injection variants, 2 arms each")
    rows = []
    t_dec_total = t_cache
    t_coup_total = 0.0
    linearity_errs = []
    for vol, rate, diff in grid:
        inj = dtp.make_injection(vol, rate, diff, q_b, args.window_extra, args.window_max)
        q_target = inj["q_total_mlps"] * 1e-6

        # --- COUPLED arm: re-solve u (at the injection's total flow) + C ---
        t0 = time.perf_counter()
        sol_c = dtp.solve_steady_stokes(dom, q_target, k_q=sol_base["k_q"])
        t_vel = time.perf_counter() - t0
        ts_c = dtp.TransportSolver(dom, sol_c, diff)
        ts_d = dtp.TransportSolver(dom, sol_base, diff)
        shared_dt = min(ts_c.dt_bound(modulation["amp"], args.cfl),
                        ts_d.dt_bound(modulation["amp"], args.cfl))
        t0 = time.perf_counter()
        res_c = ts_c.solve(inj, modulation, inj["window_s"], shared_dt=shared_dt)
        t_tr_c = time.perf_counter() - t0

        # --- DECOUPLED arm: cached u, re-solve C only ---
        t0 = time.perf_counter()
        res_d = ts_d.solve(inj, modulation, inj["window_s"], shared_dt=shared_dt)
        t_tr_d = time.perf_counter() - t0

        err = curve_error(res_d["times"], res_d["c_out"], res_c["times"], res_c["c_out"])
        t_coup = t_vel + t_tr_c
        t_dec = t_tr_d
        ratio = sol_c["f_body"] / sol_base["f_body"]
        lin_err = float(np.abs(sol_c["ux"] - ratio * sol_base["ux"]).max()
                        / max(np.abs(sol_c["ux"]).max(), 1e-300))
        linearity_errs.append(lin_err)

        peak_c, peak_d = res_c["outlet_peak"], res_d["outlet_peak"]
        row = {
            "case_id": inj["case_id"],
            "volume_ml": vol,
            "rate_mlps": rate,
            "diffusivity_m2s": diff,
            "bolus_s": inj["bolus_s"],
            "window_s": inj["window_s"],
            "dt_s": res_d["dt"],
            "n_steps": res_d["n_steps"],
            "t_velocity_s": t_vel,
            "t_transport_coupled_s": t_tr_c,
            "t_transport_decoupled_s": t_tr_d,
            "t_coupled_s": t_coup,
            "t_decoupled_s": t_dec,
            "speedup": t_coup / t_dec,
            "outlet_curve_rel_error_max": err["outlet_curve_rel_error_max"],
            "outlet_curve_rel_error_peakband": err["outlet_curve_rel_error_peakband"],
            "outlet_peak_coupled": peak_c,
            "outlet_peak_decoupled": peak_d,
            "t_half_coupled_s": t_rise_half(res_c["times"], res_c["c_out"], peak_c),
            "t_half_decoupled_s": t_rise_half(res_d["times"], res_d["c_out"], peak_d),
            "arrival_shift_s": abs(t_rise_half(res_c["times"], res_c["c_out"], peak_c)
                                   - t_rise_half(res_d["times"], res_d["c_out"], peak_d)),
            "q_target_mlps": inj["q_total_mlps"],
            "q_achieved_coupled_mlps": sol_c["q_m3s"] * 1e6,
            "solver_residual_coupled": sol_c["residual"],
            "mass_balance_rel_coupled": res_c["mass_balance_rel"],
            "mass_balance_rel_decoupled": res_d["mass_balance_rel"],
            "linearity_rescale_rel_err": lin_err,
        }
        rows.append(row)
        t_dec_total += t_dec
        t_coup_total += t_coup
        np.savez_compressed(
            os.path.join(cmp_dir, inj["case_id"] + ".npz"),
            times_dec=res_d["times"], c_out_dec=res_d["c_out"],
            times_coup=res_c["times"], c_out_coup=res_c["c_out"],
            c_in=inj["c_in"](res_c["times"]),
        )
        print(f"[compare]   {inj['case_id']:<22} vel {t_vel:6.1f}s  coup {t_coup:7.1f}s  "
              f"dec {t_dec:6.1f}s  speedup {row['speedup']:5.2f}x  err {row['outlet_curve_rel_error_max']:.4f}")

    speeds = np.array([r["speedup"] for r in rows])
    errs = np.array([r["outlet_curve_rel_error_max"] for r in rows])
    worst = rows[int(np.argmax(errs))]
    pois = dtp.validate_poiseuille(min(args.grid, 32))

    validation = {
        "poiseuille": pois,
        "solver_residual_max": float(max([sol_base["residual"]] + [r["solver_residual_coupled"] for r in rows])),
        "linearity_rescale_rel_err_max": float(max(linearity_errs)) if linearity_errs else float("nan"),
        "mass_balance_rel_max": float(max(max(r["mass_balance_rel_coupled"], r["mass_balance_rel_decoupled"])
                                          for r in rows)) if rows else 0.0,
        "flow_target_rel_err_max": float(max(abs(r["q_achieved_coupled_mlps"] - r["q_target_mlps"])
                                             / r["q_target_mlps"] for r in rows)) if rows else 0.0,
    }

    notes = [
        "The coupled arm re-solves the steady flow per injection because the power injector "
        f"materially changes the domain flow rate (Q_blood = {q_b*1e6:.2f} mL/s vs Q_inj = 1-5 mL/s). "
        "Under the strict one-way reading of the decoupling (velocity independent of injection), "
        "both arms run the identical transport discretization on identical time-step grids and the "
        "arrival curves agree to round-off; the reported error quantifies the frozen-velocity "
        "(frozen-flow-rate) approximation instead.",
        "Stokes linearity finding: the per-injection velocity solve collapses to an exact analytic "
        f"rescaling u(Q) = (Q/Q_blood) u_blood (verified to {validation['linearity_rescale_rel_err_max']:.1e}). "
        "A production decoupled predictor should therefore cache u_blood and apply the known flow-rate "
        "scaling, recovering coupled fidelity at decoupled cost; the strict frozen-u arm benchmarked "
        "here is the conservative case. (In nonlinear/in-vivo coupled CFD - non-Newtonian viscosity, "
        "fluid-structure coupling - the per-injection flow re-solve does not collapse this way.)",
        "The steady velocity model is linear Stokes (inertia neglected); at arterial Reynolds numbers "
        "O(10^2-10^3) in a mild stenosis this is the standard first-order prototype choice. Both arms "
        "use the same velocity model, so the benchmark comparison is unaffected.",
        "Arrival-curve windows are min(T_bolus + 1.5 s, 4.0 s): long injections (T_bolus up to 20 s) "
        "are recorded over their arrival transient + early plateau in both arms (identical truncation).",
        "t_decoupled_total_s includes the one-time cache build (steady velocity solve); per-injection "
        "decoupled cost is the transport re-solve alone.",
    ]

    rep = {
        "schema_version": 1,
        "tool": TOOL,
        "tool_version": VERSION,
        "command": " ".join(sys.argv),
        "created": _dt.datetime.now().isoformat(timespec="seconds"),
        "benchmark": "decoupled (u cached, C re-solved per injection) vs coupled (u + C re-solved per injection)",
        "equation": EQUATION,
        "discretization": DISCRETIZATION,
        "settings": {
            "grid": args.grid,
            "geometry": geom,
            "modulation": modulation,
            "advection_scheme": args.advection,
            "cfl": args.cfl,
            "window_extra_s": args.window_extra,
            "window_max_s": args.window_max,
            "q_blood_mlps": q_b * 1e6,
            "injection_grid": {
                "volumes_ml": _parse(args.volumes),
                "rates_mlps": _parse(args.rates),
                "diffusivities_m2s": _parse(args.diffusivities),
            },
            "dt_policy": "identical dt and step count for both arms of a variant "
                         "(min of both CFL bounds)",
        },
        # --- acceptance schema ---
        "n_variants": len(rows),
        "t_coupled_total_s": float(t_coup_total),
        "t_decoupled_total_s": float(t_dec_total),
        "speedup_mean": float(speeds.mean()) if len(rows) else float("nan"),
        "speedup_max": float(speeds.max()) if len(rows) else float("nan"),
        "outlet_curve_rel_error_max": float(errs.max()) if len(rows) else float("nan"),
        "per_variant_rows": rows,
        # --- supporting stats ---
        "speedup_distribution": {
            "min": float(speeds.min()) if len(rows) else float("nan"),
            "p25": float(np.percentile(speeds, 25)) if len(rows) else float("nan"),
            "median": float(np.median(speeds)) if len(rows) else float("nan"),
            "p75": float(np.percentile(speeds, 75)) if len(rows) else float("nan"),
            "max": float(speeds.max()) if len(rows) else float("nan"),
            "mean": float(speeds.mean()) if len(rows) else float("nan"),
            "std": float(speeds.std()) if len(rows) else float("nan"),
        },
        "speedup_histogram": histogram(list(speeds)) if len(rows) else [],
        "outlet_curve_rel_error_median": float(np.median(errs)) if len(rows) else float("nan"),
        "outlet_curve_rel_error_mean": float(errs.mean()) if len(rows) else float("nan"),
        "outlet_curve_rel_error_peakband_max": float(max(r["outlet_curve_rel_error_peakband"] for r in rows)) if rows else float("nan"),
        "outlet_curve_rel_error_worst_case": worst["case_id"] if rows else "",
        "arrival_shift_max_s": float(max(r["arrival_shift_s"] for r in rows)) if rows else float("nan"),
        "u_cache": os.path.relpath(cache_path),
        "validation": validation,
        "notes": notes,
    }
    json_path = os.path.join(out_dir, "report.json")
    with open(json_path, "w") as fh:
        json.dump(rep, fh, indent=2)
    md_path = os.path.join(out_dir, "report.md")
    with open(md_path, "w") as fh:
        fh.write(build_report_md(rep))
    print(f"[compare] wrote {json_path} and {md_path}")
    return rep


def _parse(s: str) -> tuple:
    return tuple(float(v) for v in s.split(","))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Decoupled vs coupled transport benchmark (Track 4.3)")
    ap.add_argument("--grid", type=int, default=48, help="cells per axis (benchmark range 48-64)")
    ap.add_argument("--hr", type=float, default=72.0, help="heart rate [bpm] (60-80)")
    ap.add_argument("--amp", type=float, default=0.2, help="cardiac velocity modulation amplitude a")
    ap.add_argument("--volumes", default="5,10,20", help="bolus volumes [mL]")
    ap.add_argument("--rates", default="1,2.5,5", help="injection rates [mL/s]")
    ap.add_argument("--diffusivities", default="1e-9,1e-7,1e-6", help="contrast diffusivity [m^2/s]")
    ap.add_argument("--window-extra", type=float, default=1.5, help="curve window = bolus + extra [s]")
    ap.add_argument("--window-max", type=float, default=4.0, help="max curve window [s]")
    ap.add_argument("--cfl", type=float, default=0.4)
    ap.add_argument("--advection", choices=("upwind2", "central"), default="upwind2")
    ap.add_argument("--out", default="out/transport")
    args = ap.parse_args(argv)
    run_benchmark(args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
