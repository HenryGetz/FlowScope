#!/usr/bin/env python3
"""Track 4.3 benchmark: decoupled vs coupled steady-state transport.

Arms (identical scalar discretization and time-step grids within each variant):

  DECOUPLED : the velocity field u_bar is computed ONCE (steady solve, cached to
              out/transport/u_cache.npz) and only the scalar transport
              dC/dt + u.grad C = D laplacian(C) is re-solved per injection with
              u(x,t) = u_bar(x) (1 + a sin(wt)).
  COUPLED   : u AND C are re-solved per injection: the steady flow problem is
              re-assembled and re-solved at the injection's total flow rate
              Q_blood + Q_inj (power injectors add 1-5 mL/s to ~15 mL/s of
              blood flow), then the same scalar transport is marched with that
              field.

Outputs: out/transport/report.json (machine) + out/transport/report.md (human),
per-variant curves under out/transport/compare/ .

Usage: python phase2/transport/compare.py --grid 48
"""

