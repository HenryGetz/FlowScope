EQUATION = "dC/dt + u . grad(C) = D * laplacian(C)"

DISCRETIZATION = """\
Scalar transport (finite volume, cell centred, conservative flux form):
  advection : 2nd-order upwind face reconstruction
              u_f > 0: C_f = C_L + 1/2 (C_L - C_LL);  u_f < 0: C_f = C_R - 1/2 (C_RR - C_R)
              (1st-order upwind fallback where the 2nd upwind donor cell is not fluid)
  diffusion : 2nd-order central face gradients, zero flux across lumen walls
  time      : forward Euler with CFL-controlled substepping shared by both arms,
              dt = min( CFL / sum_d max|u_d| (1+a) / h_d , 0.5 / (2 D sum_d 1/h_d^2) )
  boundary  : inlet Dirichlet bolus C_in(t) (flow-diluted square bolus, tanh edges),
              outlet advective outflow (zero-gradient ghosts).
Velocity field (computed once per anatomy in the decoupled arm, per injection in
the coupled arm): steady Stokes -mu grad^2 u + grad p = f, div u = 0 on the
staggered MAC grid of the synthetic tubular domain (streamwise periodic,
no-slip staircase lumen walls, constant body force calibrated to the target
flow rate); saddle system reduced to its SPD Schur complement and solved with
preconditioned CG.  Cardiac periodicity is imposed analytically:
  u(x,t) = u_bar(x) (1 + a sin(omega t)),  a = 0.2, HR = 72 bpm (omega = 2 pi HR/60).
"""


def curve_error(times_a, c_a, times_b, c_b, n_grid=2048):
    """max |Cb - Ca| / max(Cb) on a shared grid (peak-normalised max deviation)."""
    tgrid = np.linspace(0.0, max(times_a[-1], times_b[-1]), n_grid)
    ca = np.interp(tgrid, times_a, np.nan_to_num(c_a))
    cb = np.interp(tgrid, times_b, np.nan_to_num(c_b))
    peak_b = float(cb.max())
    denom = max(peak_b, 1e-300)
    rel = float(np.abs(cb - ca).max() / denom)
    band = cb >= 0.25 * peak_b
    # pointwise relative error inside the peak band (where the curve carries signal)
    rel_pt = float((np.abs(cb - ca)[band] / np.maximum(cb[band], 1e-12)).max()) if band.any() else float("nan")
    return {
        "outlet_curve_rel_error_max": rel,
        "outlet_curve_rel_error_peakband": rel_pt,
        "tgrid": tgrid, "ca": ca, "cb": cb,
    }


def t_rise_half(times, c, peak):
    idx = np.nonzero(c >= 0.5 * peak)[0]
    return float(times[idx[0]]) if idx.size else float("nan")


